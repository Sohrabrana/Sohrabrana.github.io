// Copies the LaTeX sources into a TypeScript module so the
// "View LaTeX source" pages are rendered at build time.
// Runs automatically before `npm run dev` and `npm run build`.
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  en: "Sohrab_Rana_CV_English.tex",
  de: "Sohrab_Rana_CV_German.tex",
};

mkdirSync(join(root, "public/cv"), { recursive: true });
const out = {};
for (const [id, name] of Object.entries(files)) {
  const src = join(root, "cv", name);
  if (!existsSync(src)) throw new Error(`Missing ${src}`);
  // Keep public/cv/*.tex in sync with cv/*.tex (the PDFs come from scripts/build-cv.sh).
  copyFileSync(src, join(root, "public/cv", name));
  out[id] = readFileSync(src, "utf8");
}

const target = join(root, "src/content/generated/cv-sources.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/sync-cv-sources.mjs. Do not edit; edit cv/*.tex instead.\n` +
    `export const cvSources: Record<"en" | "de", string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("Synced LaTeX sources:", Object.values(files).join(", "));
